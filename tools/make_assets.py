#!/usr/bin/env python3
"""Generate the LVGL images used by the UI (src/assets/*.c).

Run from the project folder:   python tools/make_assets.py
Needs Pillow (pip install pillow).

- assets/tractor.png  -> full-colour image with transparency (LV_IMG_CF_TRUE_COLOR_ALPHA, RGB565)
- icons and light beams are drawn here in code as 8-bit alpha masks (LV_IMG_CF_ALPHA_8BIT),
  so the UI can colour them (grey when off, yellow when on).
"""
import math
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "assets")
SS = 4  # supersampling for smooth edges

# Tractor drawing: crop the empty border, then scale for the Lights page
TRACTOR_SCALE = 1.2


def write_c(name, width, height, cf, data):
    path = os.path.join(OUT, name + ".c")
    with open(path, "w") as f:
        f.write("// Generated by tools/make_assets.py - do not edit by hand\n")
        f.write('#include "lvgl.h"\n\n')
        f.write("static const uint8_t %s_map[] = {\n" % name)
        for i in range(0, len(data), 24):
            f.write("    " + ", ".join("0x%02X" % b for b in data[i:i + 24]) + ",\n")
        f.write("};\n\n")
        f.write("const lv_img_dsc_t %s = {\n" % name)
        f.write("    .header.cf = %s,\n" % cf)
        f.write("    .header.always_zero = 0,\n")
        f.write("    .header.reserved = 0,\n")
        f.write("    .header.w = %d,\n" % width)
        f.write("    .header.h = %d,\n" % height)
        f.write("    .data_size = sizeof(%s_map),\n" % name)
        f.write("    .data = %s_map,\n" % name)
        f.write("};\n")
    print("wrote", path, width, "x", height)


def write_rgb565_alpha(name, im):
    im = im.convert("RGBA")
    data = bytearray()
    for r, g, b, a in list(im.getdata()):
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((c & 0xFF, c >> 8, a))  # RGB565 little endian + alpha (LV_COLOR_16_SWAP = 0)
    write_c(name, im.width, im.height, "LV_IMG_CF_TRUE_COLOR_ALPHA", data)


def write_alpha(name, mask):
    write_c(name, mask.width, mask.height, "LV_IMG_CF_ALPHA_8BIT", bytes(mask.getdata()))


def canvas(size):
    im = Image.new("L", (size * SS, size * SS), 0)
    return im, ImageDraw.Draw(im)


def finish(im, size):
    return im.resize((size, size), Image.LANCZOS)


def s(v):
    return int(v * SS)


# ---------------- Icons (drawn on a 64x64 grid, then scaled) ----------------

def icon_work_light(size, facing_right=True):
    """Lamp housing with light rays, like the ISO 7000 work light symbol."""
    im, d = canvas(size)
    k = size / 64.0
    # lamp body: a "D" shape
    body = [s(6 * k), s(16 * k), s(34 * k), s(48 * k)]
    d.rounded_rectangle(body, radius=s(6 * k), fill=255)
    d.pieslice([s(18 * k), s(16 * k), s(50 * k), s(48 * k)], -90, 90, fill=255)
    # lens cut-out
    d.pieslice([s(24 * k), s(21 * k), s(44 * k), s(43 * k)], -90, 90, fill=0)
    # rays
    for y in (18, 32, 46):
        d.line([s(48 * k), s(y * k), s(60 * k), s((y + (y - 32) * 0.35) * k)], fill=255, width=s(4.5 * k))
    im = finish(im, size)
    return im if facing_right else im.transpose(Image.FLIP_LEFT_RIGHT)


def icon_beacon(size):
    """Rotating beacon: dome on a base with rays."""
    im, d = canvas(size)
    k = size / 64.0
    d.rounded_rectangle([s(16 * k), s(46 * k), s(48 * k), s(56 * k)], radius=s(3 * k), fill=255)
    d.pieslice([s(20 * k), s(24 * k), s(44 * k), s(68 * k)], 180, 360, fill=255)
    d.rectangle([s(20 * k), s(44 * k), s(44 * k), s(47 * k)], fill=255)
    d.pieslice([s(27 * k), s(31 * k), s(37 * k), s(52 * k)], 180, 360, fill=0)  # highlight
    for angle in (-160, -125, -90, -55, -20):
        a = math.radians(angle)
        cx, cy = 32, 40
        x1, y1 = cx + math.cos(a) * 21, cy + math.sin(a) * 21
        x2, y2 = cx + math.cos(a) * 30, cy + math.sin(a) * 30
        d.line([s(x1 * k), s(y1 * k), s(x2 * k), s(y2 * k)], fill=255, width=s(4.5 * k))
    return finish(im, size)


def icon_camera(size):
    im, d = canvas(size)
    k = size / 64.0
    d.rounded_rectangle([s(4 * k), s(18 * k), s(60 * k), s(54 * k)], radius=s(7 * k), fill=255)
    d.rounded_rectangle([s(20 * k), s(10 * k), s(44 * k), s(22 * k)], radius=s(4 * k), fill=255)
    d.ellipse([s(19 * k), s(23 * k), s(45 * k), s(49 * k)], fill=0)
    d.ellipse([s(24 * k), s(28 * k), s(40 * k), s(44 * k)], fill=255)
    return finish(im, size)


def icon_isobus(size):
    """Round 9-pin ISOBUS breakaway connector seen from the front."""
    im, d = canvas(size)
    k = size / 64.0
    d.ellipse([s(4 * k), s(4 * k), s(60 * k), s(60 * k)], fill=255)
    d.ellipse([s(10 * k), s(10 * k), s(54 * k), s(54 * k)], fill=0)
    d.rectangle([s(28 * k), s(2 * k), s(36 * k), s(10 * k)], fill=0)  # key notch
    pins = [(32, 32)] + [(32 + math.cos(math.radians(a)) * 14, 32 + math.sin(math.radians(a)) * 14) for a in range(-90, 270, 45)]
    for x, y in pins:
        d.ellipse([s((x - 3.6) * k), s((y - 3.6) * k), s((x + 3.6) * k), s((y + 3.6) * k)], fill=255)
    return finish(im, size)


def icon_power(size):
    im, d = canvas(size)
    k = size / 64.0
    d.arc([s(10 * k), s(12 * k), s(54 * k), s(56 * k)], -60, 240, fill=255, width=s(6 * k))
    d.line([s(32 * k), s(6 * k), s(32 * k), s(32 * k)], fill=255, width=s(6 * k))
    return finish(im, size)


# ---------------- Light effects ----------------

def beam(length, spread, facing_right=True):
    """Soft cone of light, brightest at the lamp, fading out, aimed slightly down.
    The lamp sits at the left edge, 30 % down from the top."""
    w, h = length, spread
    im = Image.new("L", (w, h), 0)
    px = im.load()
    lamp_y = h * 0.30
    for x in range(w):
        t = x / float(w - 1)
        centre = lamp_y + t * h * 0.32          # aims downwards
        half = 3.0 + t * h * 0.36               # widens with distance
        fade = (1.0 - t) ** 2.2 * min(1.0, t * 12.0 + 0.35)
        for y in range(h):
            d = abs(y - centre) / half
            if d < 1.0:
                edge = (1.0 - d * d) ** 2       # smooth to zero at the edge
                px[x, y] = int(230 * fade * edge)
    return im if facing_right else im.transpose(Image.FLIP_LEFT_RIGHT)


def glow(size):
    im = Image.new("L", (size, size), 0)
    px = im.load()
    c = (size - 1) / 2.0
    for y in range(size):
        for x in range(size):
            r = math.hypot(x - c, y - c) / c
            if r < 1.0:
                px[x, y] = int(255 * (1.0 - r) ** 1.8)
    return im


def main():
    os.makedirs(OUT, exist_ok=True)

    tractor = Image.open(os.path.join(ROOT, "assets", "tractor.png")).convert("RGBA")
    tractor = tractor.crop(tractor.getchannel("A").point(lambda v: 255 if v > 10 else 0).getbbox())
    tractor = tractor.resize((int(tractor.width * TRACTOR_SCALE), int(tractor.height * TRACTOR_SCALE)), Image.LANCZOS)
    write_rgb565_alpha("img_tractor", tractor)

    write_alpha("img_icon_lights", icon_work_light(44))
    write_alpha("img_icon_isobus", icon_isobus(44))
    write_alpha("img_icon_camera", icon_camera(44))
    write_alpha("img_icon_front", icon_work_light(48, facing_right=True))
    write_alpha("img_icon_rear", icon_work_light(48, facing_right=False))
    write_alpha("img_icon_beacon", icon_beacon(48))
    write_alpha("img_icon_power", icon_power(28))
    write_alpha("img_icon_camera_big", icon_camera(96))

    write_alpha("img_beam_front", beam(210, 150, facing_right=True))
    write_alpha("img_beam_rear", beam(210, 150, facing_right=False))
    write_alpha("img_glow", glow(64))


if __name__ == "__main__":
    main()
